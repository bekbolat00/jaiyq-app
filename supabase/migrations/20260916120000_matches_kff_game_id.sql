-- Идентификатор игры на kffleague.kz.
--
-- Импорт сопоставлял матч по паре (дата, дома/в гостях). Пока импорт
-- запускался руками, этого хватало, но автосинхронизация
-- (app/api/cron/sync-matches) будет молча плодить дубли, как только KFF
-- перенесёт игру на другой день: новой даты в БД нет — создаётся новая
-- строка, а старая навсегда остаётся «предстоящей».
--
-- С этой колонкой матч находится по id KFF, а дата/время переносятся в
-- существующую строку. Импорт проверяет наличие колонки и без неё
-- работает по-старому.

alter table public.matches
  add column if not exists kff_game_id integer;

create unique index if not exists matches_kff_game_id_key
  on public.matches (kff_game_id);
