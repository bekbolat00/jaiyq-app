-- Позиция игрока В КОНКРЕТНОМ МАТЧЕ.
--
-- `players.position` — канонная позиция игрока по ростеру сезона, но на
-- тактической доске нужна роль именно в этой игре: KFF (и наш референс)
-- показывают, например, Чиркова и Якуди нападающими в матче 28.08.2026,
-- хотя в ростере они полузащитники. Без этой колонки схема на поле
-- получается вида «4-6» вместо реальной 4-4-2.
--
-- Имя выбрано под уже существующее ожидание фронтенда:
-- `lineFromRow()` / `toLinePlayerFromDb()` читают `position_override`
-- и падают обратно на `players.position`, так что после применения
-- миграции и повторного запуска `scripts/importSeason.js` поле начнёт
-- строить составы по реальным ролям без правок в коде приложения.

alter table public.match_lineups
  add column if not exists position_override text;
